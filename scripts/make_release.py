# Hard size guard: never ship an individual file larger than this. Weight blobs
# and derived corpora are excluded above; this catches anything new that lands in
# the tree later.
MAX_FILE_BYTES = 5 * 1024 * 1024
EXCLUDE_DIR_NAMES = {
    "__pycache__", ".git", ".idea", ".vscode",
}
EXCLUDE_FILE_EXTS = {".pyc", ".pyo", ".DS_Store", ".thumbs.db"}


def should_include(rel_posix: str) -> bool:
    for d in EXCLUDE_DIR_NAMES:
        if d in rel_posix.split("/"):
            return False
    if any(rel_posix.startswith(pfx) for pfx in EXCLUDE_PATH_PREFIXES):
        return False
    if any(rel_posix.lower().endswith(ext) for ext in EXCLUDE_FILE_EXTS):
        return False
    return True


def main():
    # Build the archive directly from the source tree. No staging directory is
    # created, so no bulk rmtree is needed on the way out. Entries keep the
    # published prefix `sentiment-system-release/sentiment-system/...` so the
    # package layout stays drop-in compatible with prior releases.
    if ZIP_PATH.exists():
        ZIP_PATH.unlink()
    copied, skipped = 0, 0
    with zipfile.ZipFile(ZIP_PATH, "w", zipfile.ZIP_DEFLATED) as zf:
        for p in ROOT.rglob("*"):
            if p.is_dir():
                continue
            rel = str(p.relative_to(ROOT)).replace("\\", "/")
            if not should_include(rel):
                skipped += 1
                continue
            if p.stat().st_size > MAX_FILE_BYTES:
                print(f"skip (>{MAX_FILE_BYTES // (1024 * 1024)} MB) {rel}: "
                      f"{p.stat().st_size:,} bytes")
                skipped += 1
                continue
            arcname = "sentiment-system-release/" + rel
            zf.write(p, arcname)
            copied += 1
    print(f"copied {copied} files, skipped {skipped}")
    print(f"zipped -> {ZIP_PATH}  ({ZIP_PATH.stat().st_size:,} bytes)")
    print("done")


if __name__ == "__main__":
    main()
